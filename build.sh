#!/bin/bash
# Concatenates src/*.zsh (filename order) into the shippable single-file artifact.
# First generates src/90a-lada-glass-assets.zsh from the vendored Låda Glass design system
# (vendor/lada-glass/<version>/), so the HTML dashboard is styled without any file or network
# access at run time.
set -euo pipefail

SRC_DIR="${1:-src}"
OUT_FILE="${2:-Invoke-MacPostureCheck.sh}"
LADA_DIR="${LADA_DIR:-vendor/lada-glass/1.1.1}"
ASSETS_MODULE="$SRC_DIR/90a-lada-glass-assets.zsh"

if [[ ! -d "$SRC_DIR" ]]; then
    echo "Source directory not found: $SRC_DIR" >&2
    exit 1
fi
for asset in lada-glass.css sprite.svg VERSION; do
    if [[ ! -f "$LADA_DIR/$asset" ]]; then
        echo "Låda Glass asset missing: $LADA_DIR/$asset" >&2
        exit 1
    fi
done

{
    echo "#!/usr/bin/env zsh"
    echo "#"
    echo "# Låda Glass $(tr -d '[:space:]' < "$LADA_DIR/VERSION") assets for the HTML dashboard."
    echo "# Generated by build.sh from $LADA_DIR. Do not edit; update the vendored copy instead."
    echo ""
    echo "typeset -g LADA_GLASS_VERSION='$(tr -d '[:space:]' < "$LADA_DIR/VERSION")'"
    echo "typeset -g LADA_GLASS_CSS LADA_GLASS_SPRITE"
    echo "read -r -d '' LADA_GLASS_CSS <<'LADA_GLASS_CSS_EOF'"
    cat "$LADA_DIR/lada-glass.css"
    echo "LADA_GLASS_CSS_EOF"
    echo "read -r -d '' LADA_GLASS_SPRITE <<'LADA_GLASS_SPRITE_EOF'"
    cat "$LADA_DIR/sprite.svg"
    echo "LADA_GLASS_SPRITE_EOF"
} > "$ASSETS_MODULE"

{
    echo "#!/usr/bin/env zsh"
    echo "# EndpointPostureCheck for macOS — built $(date '+%Y-%m-%d %H:%M:%S') from src/*.zsh. Do not edit directly."
    for f in "$SRC_DIR"/*.zsh; do
        echo ""
        echo "# ---- $(basename "$f") ----"
        # Drop each module's own shebang line; only the top-level shebang above is kept.
        tail -n +2 "$f"
    done
} > "$OUT_FILE"

chmod +x "$OUT_FILE"
module_count=$(find "$SRC_DIR" -maxdepth 1 -name '*.zsh' | wc -l | tr -d ' ')
echo "Built $OUT_FILE from $module_count source file(s) (Låda Glass $(tr -d '[:space:]' < "$LADA_DIR/VERSION"))."
