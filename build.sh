#!/bin/bash
# Concatenates src/*.zsh (filename order) into the shippable single-file artifact.
# First generates src/90a-lada-glass-assets.zsh from the vendored Låda Glass design system
# (vendor/lada-glass/<version>/), so the HTML dashboard is styled without any file or network
# access at run time.
set -euo pipefail

SRC_DIR="${1:-src}"
OUT_FILE="${2:-Invoke-MacPostureCheck.sh}"
LADA_DIR="${LADA_DIR:-vendor/lada-glass/1.1.1}"
ASSETS_MODULE="$SRC_DIR/90a-lada-glass-assets.zsh"

if [[ ! -d "$SRC_DIR" ]]; then
    echo "Source directory not found: $SRC_DIR" >&2
    exit 1
fi
for asset in lada-glass.css sprite.svg VERSION; do
    if [[ ! -f "$LADA_DIR/$asset" ]]; then
        echo "Låda Glass asset missing: $LADA_DIR/$asset" >&2
        exit 1
    fi
done

{
    echo "#!/usr/bin/env zsh"
    echo "#"
    echo "# Låda Glass $(tr -d '[:space:]' < "$LADA_DIR/VERSION") assets for the HTML dashboard."
    echo "# Generated by build.sh from $LADA_DIR. Do not edit; update the vendored copy instead."
    echo ""
    echo "typeset -g LADA_GLASS_VERSION='$(tr -d '[:space:]' < "$LADA_DIR/VERSION")'"
    echo "typeset -g LADA_GLASS_CSS LADA_GLASS_SPRITE"
    echo "read -r -d '' LADA_GLASS_CSS <<'LADA_GLASS_CSS_EOF'"
    cat "$LADA_DIR/lada-glass.css"
    echo "LADA_GLASS_CSS_EOF"
    echo "read -r -d '' LADA_GLASS_SPRITE <<'LADA_GLASS_SPRITE_EOF'"
    cat "$LADA_DIR/sprite.svg"
    echo "LADA_GLASS_SPRITE_EOF"
} > "$ASSETS_MODULE"

{
    echo "#!/usr/bin/env zsh"
    echo "# EndpointPostureCheck for macOS — built $(date '+%Y-%m-%d %H:%M:%S') from src/*.zsh. Do not edit directly."
    for f in "$SRC_DIR"/*.zsh; do
        echo ""
        echo "# ---- $(basename "$f") ----"
        # Drop each module's own shebang line; only the top-level shebang above is kept.
        tail -n +2 "$f"
    done
} > "$OUT_FILE"

chmod +x "$OUT_FILE"

# One version number: VERSION is the source. Both scripts run standalone and can't read it at
# run time, so it is stamped into the macOS build and the Windows script here (CI checks all three).
APP_VERSION=$(tr -d '[:space:]' < VERSION)
if [[ ! "$APP_VERSION" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]]; then
    echo "VERSION must be MAJOR.MINOR.PATCH, got: $APP_VERSION" >&2
    exit 1
fi
perl -pi -e 's/^SCRIPT_VERSION="[^"]*"/SCRIPT_VERSION="'"$APP_VERSION"'"/' "$OUT_FILE"
if [[ $(grep -c "^SCRIPT_VERSION=\"$APP_VERSION\"$" "$OUT_FILE") -ne 1 ]]; then
    echo "Could not stamp version $APP_VERSION into $OUT_FILE" >&2
    exit 1
fi
module_count=$(find "$SRC_DIR" -maxdepth 1 -name '*.zsh' | wc -l | tr -d ' ')
echo "Built $OUT_FILE from $module_count source file(s) (Låda Glass $(tr -d '[:space:]' < "$LADA_DIR/VERSION"))."

# The Windows edition is a single hand-maintained .ps1 with no build of its own; only the
# region between the LADA-GLASS-ASSETS markers is generated here, from the same vendored copy.
# The .ps1 stays pure ASCII (Windows PowerShell 5.1 reads a BOM-less script as ANSI), so any
# non-ASCII character in the CSS becomes a CSS escape (harmless in comments, valid in strings).
WIN_FILE="${WIN_FILE:-Invoke-EndpointPostureCheck.ps1}"
BEGIN_MARK='# >>> LADA-GLASS-ASSETS (generated by build.sh from vendor/lada-glass; do not edit)'
END_MARK='# <<< LADA-GLASS-ASSETS'
if [[ -f "$WIN_FILE" ]] && grep -qF "$BEGIN_MARK" "$WIN_FILE" && grep -qF "$END_MARK" "$WIN_FILE"; then
    to_ascii() { perl -CSD -pe 's/([^\x00-\x7F])/sprintf("\\%X ", ord($1))/ge' "$1"; }
    region=$(mktemp)
    {
        echo "$BEGIN_MARK"
        echo "function Get-LadaGlassAsset {"
        echo "    # Låda Glass $(tr -d '[:space:]' < "$LADA_DIR/VERSION") design system, inlined so the report is one offline file." | perl -CSD -pe 's/\x{e5}/a/g'
        echo "    return @{"
        echo "        Version = '$(tr -d '[:space:]' < "$LADA_DIR/VERSION")'"
        echo "        Css     = @'"
        to_ascii "$LADA_DIR/lada-glass.css"
        echo "'@"
        echo "        Sprite  = @'"
        to_ascii "$LADA_DIR/sprite.svg"
        echo "'@"
        echo "    }"
        echo "}"
        echo "$END_MARK"
    } > "$region"
    # Exactly two lines may start with '@: the two here-string terminators written above.
    if [[ $(grep -c "^'@" "$region") -ne 2 ]]; then
        echo "Låda Glass assets contain a line starting with '@ (would end the here-string)" >&2
        rm -f "$region"; exit 1
    fi
    awk -v begin="$BEGIN_MARK" -v end="$END_MARK" -v regionfile="$region" '
        $0 == begin { while ((getline line < regionfile) > 0) print line; skip = 1; next }
        $0 == end   { skip = 0; next }
        !skip       { print }
    ' "$WIN_FILE" > "$WIN_FILE.tmp" && mv "$WIN_FILE.tmp" "$WIN_FILE"
    rm -f "$region"
    if LC_ALL=C grep -q '[^ -~	]' "$WIN_FILE"; then
        echo "$WIN_FILE contains non-ASCII characters after the asset sync" >&2
        exit 1
    fi
    echo "Synced Låda Glass assets into $WIN_FILE."
fi
if [[ -f "$WIN_FILE" ]]; then
    perl -pi -e 's/^(\$Script:ScriptVersion\s*=\s*)\x27[^\x27]*\x27/${1}\x27'"$APP_VERSION"'\x27/' "$WIN_FILE"
    if ! grep -q "^\$Script:ScriptVersion *= *'$APP_VERSION'" "$WIN_FILE"; then
        echo "Could not stamp version $APP_VERSION into $WIN_FILE" >&2
        exit 1
    fi
fi
echo "Version $APP_VERSION."
